#!/usr/bin/env node
// test-release-binary.mjs: tests of the release tool's planning (tools/release-binary.mjs, everything short of the
// cargo build): the naming, the version crate, the lock check and the releases URL, for rbxts-rs's own release (the
// defaults) and for a plugin repo's (flamework-rs's), the latter against a scratch fake: a git repo with the text
// files, a lock, a tag and an `origin`, and a skeleton in a git repo of its own pinning a crate from it.
//
//   node tools/test-release-binary.mjs

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
	githubRepo,
	gitDependencies,
	lockDifferences,
	lockedElsewhere,
	parseArgs,
	prepareRelease,
	presetProblems,
	releaseNames,
	releasesUrl,
	releaseZip,
	versionCrate,
} from "./release-binary.mjs";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKELETON = path.join(REPO, "templates", "compiler");
const launcher = await import(pathToFileURL(path.join(SKELETON, "rbxtsc.mjs")).href);
const ROOT = fs.mkdtempSync(path.join(os.tmpdir(), "rbxtsc-release-test-"));

let passed = 0;
let failures = 0;
async function test(name, body) {
	try {
		await body();
		passed++;
		console.log(`ok   ${name}`);
	} catch (e) {
		failures++;
		console.log(`FAIL ${name}\n     ${e.message.replaceAll("\n", "\n     ")}`);
	}
}

function assert(condition, message, detail = "") {
	if (!condition) throw new Error(`${message}${detail ? `\n${detail}` : ""}`);
}

function equal(actual, expected, message) {
	const [a, e] = [JSON.stringify(actual), JSON.stringify(expected)];
	assert(a === e, message, `expected ${e}\n  actual ${a}`);
}

async function rejects(promise, pattern, message) {
	try {
		await promise;
	} catch (e) {
		assert(pattern.test(e.message), message, e.message);
		return e.message;
	}
	throw new Error(`${message}: no error`);
}

function throws(body, pattern, message) {
	try {
		body();
	} catch (e) {
		assert(pattern.test(e.message), message, e.message);
		return;
	}
	throw new Error(`${message}: no error`);
}

const GIT_ENV = { ...process.env, GIT_AUTHOR_NAME: "t", GIT_AUTHOR_EMAIL: "t@example.com", GIT_COMMITTER_NAME: "t", GIT_COMMITTER_EMAIL: "t@example.com" };
function git(cwd, ...args) {
	const r = spawnSync("git", ["-C", cwd, "-c", "core.autocrlf=false", "-c", "commit.gpgsign=false", "-c", "tag.gpgsign=false", ...args], { env: GIT_ENV });
	if (r.status !== 0) throw new Error(`git ${args.join(" ")}: ${r.stderr}`);
	return r.stdout.toString().trim();
}

function write(dir, files) {
	for (const [name, text] of Object.entries(files)) {
		fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
		fs.writeFileSync(path.join(dir, name), text);
	}
}

const lockPackage = (name, version, source) => `[[package]]\nname = "${name}"\nversion = "${version}"\n${source ? `source = "${source}"\n` : ""}`;
const lock = (...packages) => `# This file is automatically @generated by Cargo.\nversion = 4\n\n${packages.join("\n")}`;
const RBXTS = "git+https://github.com/rbxts-rs/rbxts-rs?tag=v0.1.1#306c3e0c4bca6286e945be80268a86965f924206";
const RBXTS_OLD = "git+https://github.com/rbxts-rs/rbxts-rs?tag=v0.1.0#0fa1528d821129133e989ab1178513a11891044e";
const FAKE_FW = "git+https://github.com/example/fake-fw?tag=v0.1.0#1111111111111111111111111111111111111111";
const CRATES_IO = "registry+https://github.com/rust-lang/crates.io-index";

// flamework-rs's shape: its own crates as path packages, rbxts-rs's as git packages
const repoLock = (rbxts = RBXTS) =>
	lock(lockPackage("fake_fw", "0.1.0"), lockPackage("rbxts_cli", "0.1.1", rbxts), lockPackage("rbxts_plugin", "0.1.1", rbxts), lockPackage("serde", "1.0.200", CRATES_IO));
// the skeleton's: everything from git or crates.io, the skeleton package itself a path package
const skeletonLock = (rbxts = RBXTS, fw = FAKE_FW) =>
	lock(
		lockPackage("fake_fw", "0.1.0", fw),
		lockPackage("rbxts_cli", "0.1.1", rbxts),
		lockPackage("rbxts_plugin", "0.1.1", rbxts),
		lockPackage("rbxtsc-fw", "0.0.0"),
		lockPackage("serde", "1.0.200", CRATES_IO),
	);
const FW_TOML = `[package]
name = "rbxtsc-fw"
version = "0.0.0"
edition = "2024"

[workspace]

[[bin]]
name = "rbxtsc-fw"
path = "src/main.rs"

[dependencies]
rbxts_cli = { git = "https://github.com/rbxts-rs/rbxts-rs", tag = "v0.1.1" }
fake_fw = { git = "https://github.com/example/fake-fw.git", tag = "v0.1.0" }
# other_plugin = { git = "https://github.com/example/fake-fw", tag = "v9.9.9" }
`;

try {
	await test("githubRepo / releasesUrl: https and ssh remotes, with and without .git; others are not GitHub", () => {
		for (const remote of [
			"https://github.com/rbxts-rs/flamework-rs.git",
			"https://github.com/rbxts-rs/flamework-rs",
			"https://github.com/rbxts-rs/flamework-rs/",
			"git@github.com:rbxts-rs/flamework-rs.git",
			"ssh://git@github.com/rbxts-rs/flamework-rs.git",
			"https://user@github.com/rbxts-rs/flamework-rs.git\n",
		]) {
			equal(githubRepo(remote), { url: "https://github.com/rbxts-rs/flamework-rs", owner: "rbxts-rs", name: "flamework-rs" }, remote);
		}
		equal(releasesUrl(githubRepo("https://github.com/rbxts-rs/rbxts-rs.git")), "https://github.com/rbxts-rs/rbxts-rs/releases/download", "rbxts-rs");
		for (const remote of ["", undefined, "https://gitlab.com/a/b.git", "E:/some/local/repo", "https://github.com/only-owner"]) {
			equal(githubRepo(remote), undefined, String(remote));
		}
	});

	await test("releaseNames: the versioned zip is named after the repo, the fixed one after the preset's bin", () => {
		equal(releaseNames({ name: "flamework-rs", version: "0.1.0", platform: "windows-x64", bin: "rbxtsc-fw" }), { versioned: "flamework-rs-0.1.0-windows-x64.zip", fixed: "rbxtsc-fw-windows-x64.zip" }, "flamework-rs");
		equal(releaseNames({ name: "rbxts-rs", version: "0.1.1", platform: "windows-x64", bin: "rbxtsc" }), { versioned: "rbxts-rs-0.1.1-windows-x64.zip", fixed: "rbxtsc-windows-x64.zip" }, "rbxts-rs");
	});

	await test("versionCrate: the dependency from the release repo's remote; --version-crate overrides", () => {
		const skeletonToml = fs.readFileSync(path.join(SKELETON, "Cargo.toml"), "utf8");
		equal(versionCrate(skeletonToml, "https://github.com/rbxts-rs/rbxts-rs"), { crate: "rbxts_cli", version: "0.1.1" }, "rbxts-rs's skeleton");
		equal(gitDependencies(FW_TOML).map((d) => d.crate), ["rbxts_cli", "fake_fw"], "commented-out dependencies are not read");
		equal(versionCrate(FW_TOML, "https://github.com/example/fake-fw"), { crate: "fake_fw", version: "0.1.0" }, "the plugin repo's crate (a .git URL in Cargo.toml)");
		equal(versionCrate(FW_TOML, "https://github.com/rbxts-rs/rbxts-rs"), { crate: "rbxts_cli", version: "0.1.1" }, "rbxts-rs's crate in the same skeleton");
		equal(versionCrate(FW_TOML, undefined, "fake_fw"), { crate: "fake_fw", version: "0.1.0" }, "--version-crate without a remote");
		equal(versionCrate(FW_TOML, "https://github.com/example/fake-fw", "rbxts_cli"), { crate: "rbxts_cli", version: "0.1.1" }, "--version-crate wins over the remote");
		throws(() => versionCrate(FW_TOML, "https://github.com/example/elsewhere"), /no git dependency on https:\/\/github.com\/example\/elsewhere: .*--version-crate/, "no dependency from the remote");
		throws(() => versionCrate(FW_TOML, undefined), /no GitHub origin remote.*--version-crate/, "no remote");
		throws(() => versionCrate(FW_TOML, undefined, "nope"), /no git dependency nope/, "an unknown --version-crate");
		const split = `${FW_TOML}fake_fw_macros = { git = "https://github.com/example/fake-fw", tag = "v0.2.0" }\n`;
		throws(() => versionCrate(split, "https://github.com/example/fake-fw"), /fake_fw, fake_fw_macros pin different tags \(v0\.1\.0, v0\.2\.0\)/, "two crates of the repo at different tags");
		const same = `${FW_TOML}fake_fw_macros = { git = "https://github.com/example/fake-fw", tag = "v0.1.0" }\n`;
		equal(versionCrate(same, "https://github.com/example/fake-fw"), { crate: "fake_fw", version: "0.1.0" }, "two crates of the repo at one tag");
		const byRev = FW_TOML.replace('tag = "v0.1.0"', 'rev = "abc"');
		throws(() => versionCrate(byRev, "https://github.com/example/fake-fw"), /fake_fw has no `tag = "v<version>"`/, "a rev pin");
	});

	await test("lockDifferences: rbxts-rs's skeleton against its workspace lock at v0.1.1 (path packages skipped, as before)", () => {
		const skeleton = fs.readFileSync(path.join(SKELETON, "Cargo.lock"), "utf8");
		const workspace = spawnSync("git", ["-C", REPO, "show", "v0.1.1:Cargo.lock"]).stdout.toString();
		assert(workspace.includes('name = "rbxts_cli"'), "the workspace lock at v0.1.1");
		equal(lockDifferences(skeleton, workspace), [], "no differences");
		// the crates the old rule skipped (every rbxts_*) are exactly the ones the new rule skips: path packages there
		const changed = skeleton.replaceAll(/^(source = "git\+https:\/\/github\.com\/rbxts-rs\/rbxts-rs\?tag=)v0\.1\.1/gm, "$1v0.0.9");
		assert(changed !== skeleton, "the skeleton lock has rbxts-rs git packages");
		equal(lockDifferences(changed, workspace), [], "rbxts-rs's own crates are not compared with its workspace");
	});

	await test("lockedElsewhere: the release repo's crates locked at another commit than the ref's", () => {
		const at = "1111111111111111111111111111111111111111";
		equal(lockedElsewhere(skeletonLock(), "https://github.com/example/fake-fw", at), [], "locked at the ref's commit");
		equal(lockedElsewhere(skeletonLock(), "https://github.com/example/fake-fw", "2".repeat(40)), ["fake_fw at 111111111111"], "another commit");
		equal(lockedElsewhere(skeletonLock(), "https://github.com/rbxts-rs/rbxts-rs", "306c3e0c4bca"), [], "rbxts-rs at its tag, by a short commit");
		equal(lockedElsewhere(skeletonLock(), "https://github.com/rbxts-rs/rbxts-rs", "0fa1528d8211"), ["rbxts_cli at 306c3e0c4bca", "rbxts_plugin at 306c3e0c4bca"], "rbxts-rs at another commit");
	});

	await test("lockDifferences: a plugin repo's lock with rbxts-rs's crates as git packages compares them too", () => {
		equal(lockDifferences(skeletonLock(), repoLock()), [], "the same rbxts-rs tag");
		equal(
			lockDifferences(skeletonLock(RBXTS_OLD), repoLock()),
			[
				`rbxts_cli: 0.1.1 ${RBXTS_OLD}, the repo's lock 0.1.1 ${RBXTS}`,
				`rbxts_plugin: 0.1.1 ${RBXTS_OLD}, the repo's lock 0.1.1 ${RBXTS}`,
			],
			"another rbxts-rs tag",
		);
		const moved = RBXTS.replace(/#.*$/, "#0000000000000000000000000000000000000000");
		equal(
			lockDifferences(skeletonLock(moved), repoLock()).length,
			2,
			"the same tag at another commit (a moved tag) differs too",
		);
		const extra = skeletonLock() + "\n" + lockPackage("extra", "1.0.0", CRATES_IO);
		equal(lockDifferences(extra, repoLock()), [`extra: 1.0.0 ${CRATES_IO} (not in the repo's lock)`], "a crate the repo does not have");
	});

	await test("presetProblems: the messages name the skeleton and the version crate", () => {
		const problems = presetProblems({ config: "x", version: "9.9.9" }, "h", "0.1.0", { skeleton: "E:/x/compiler", crate: "flamework_rs" });
		equal(problems, ['"config" is "x": set it to "h" (`node E:/x/compiler/rbxtsc.mjs --where` prints it)', '"version" is "9.9.9": set it to "0.1.0" (the tag flamework_rs pins in Cargo.toml)'], "problems");
	});

	await test("prepareRelease: the defaults are rbxts-rs's release, as the committed preset has it", async () => {
		const cwd = process.cwd();
		process.chdir(REPO);
		try {
			const plan = await prepareRelease(parseArgs([]));
			const preset = JSON.parse(fs.readFileSync(path.join(SKELETON, "preset.json"), "utf8"));
			equal([plan.name, plan.crate, plan.version, plan.ref, plan.where], ["rbxts-rs", "rbxts_cli", "0.1.1", "v0.1.1", "templates/compiler"], "plan");
			equal(plan.problems, [], "the preset matches");
			equal(plan.versioned, `rbxts-rs-0.1.1-${plan.platform}.zip`, "versioned zip");
			equal(plan.fixed, `rbxtsc-${plan.platform}.zip`, "fixed zip");
			if (preset.binaries?.[plan.triple]) equal(plan.url, preset.binaries[plan.triple].url, "the preset's url");
		} finally {
			process.chdir(cwd);
		}
	});

	// the fake plugin repo and its project's skeleton
	const fakeRepo = path.join(ROOT, "fake-fw-checkout");
	write(fakeRepo, { LICENSE: "MIT fake\n", "THIRD-PARTY-NOTICES.md": "# notices\n", "README.md": "# fake-fw\r\nCRLF kept\r\n", "Cargo.lock": repoLock() });
	git(fakeRepo, "init", "-q", "-b", "main");
	git(fakeRepo, "add", "-A");
	git(fakeRepo, "commit", "-q", "-m", "release 0.1.0");
	git(fakeRepo, "tag", "v0.1.0");
	git(fakeRepo, "remote", "add", "origin", "git@github.com:example/fake-fw.git");
	const tagCommit = git(fakeRepo, "rev-parse", "HEAD");
	write(fakeRepo, { "Cargo.lock": repoLock(RBXTS_OLD) });
	git(fakeRepo, "commit", "-q", "-am", "move to an older rbxts-rs");

	const template = path.join(ROOT, "fake-template");
	const skeleton = path.join(template, "compiler");
	for (const name of ["rbxtsc.mjs", "rust-toolchain.toml", ".cargo/config.toml", "src/main.rs"]) {
		write(skeleton, { [name]: fs.readFileSync(path.join(SKELETON, name)) });
	}
	write(skeleton, { "Cargo.toml": FW_TOML, "Cargo.lock": skeletonLock(RBXTS, FAKE_FW.replace(/#.*$/, `#${tagCommit}`)) });
	const hash = launcher.configHash(skeleton);
	write(skeleton, { "preset.json": JSON.stringify({ bin: "rbxtsc-fw", version: "0.1.0", config: hash, binaries: {} }, null, "\t") + "\n" });
	write(template, { "package.json": "{}\n" });
	git(template, "init", "-q", "-b", "main");
	git(template, "add", "-A");
	git(template, "commit", "-q", "-m", "template");
	const fw = (...args) => parseArgs(["--skeleton", skeleton, "--repo", fakeRepo, ...args]);

	await test("prepareRelease: a plugin repo's release from its project's skeleton", async () => {
		const plan = await prepareRelease(fw());
		equal([plan.name, plan.crate, plan.version, plan.ref, plan.commit], ["fake-fw", "fake_fw", "0.1.0", "v0.1.0", tagCommit], "plan");
		equal([plan.versioned, plan.fixed], [`fake-fw-0.1.0-${plan.platform}.zip`, `rbxtsc-fw-${plan.platform}.zip`], "zip names");
		equal(plan.exeName, process.platform === "win32" ? "rbxtsc-fw.exe" : "rbxtsc-fw", "the binary is the preset's bin");
		equal(plan.url, `https://github.com/example/fake-fw/releases/download/v0.1.0/fake-fw-0.1.0-${plan.platform}.zip`, "url from the ssh origin");
		equal(plan.hash, hash, "config hash");
		equal(plan.where, skeleton.replaceAll("\\", "/"), "messages name the skeleton (outside the current folder: absolute)");
		const renamed = await prepareRelease(fw("--name", "other", "--releases", "https://example.com/dl/"));
		equal(renamed.url, `https://example.com/dl/v0.1.0/other-0.1.0-${plan.platform}.zip`, "--name and --releases");
	});

	await test("releaseZip: the binary first, then the text files of the release repo at the tag, byte for byte", async () => {
		const plan = await prepareRelease(fw());
		const zip = releaseZip({ repo: fakeRepo, commit: plan.commit, ref: plan.ref, exe: Buffer.from("fake exe"), exeName: plan.exeName });
		equal(launcher.zipEntries(zip).map((e) => e.name), [plan.exeName, "LICENSE", "THIRD-PARTY-NOTICES.md", "README.md"], "entries");
		equal(launcher.extractExe(zip, plan.exeName).toString(), "fake exe", "the binary");
		const readme = launcher.zipEntries(zip).find((e) => e.name === "README.md");
		equal(launcher.zipEntryBytes(zip, readme).toString(), "# fake-fw\r\nCRLF kept\r\n", "README.md as committed");
		const again = releaseZip({ repo: fakeRepo, commit: plan.commit, ref: plan.ref, exe: Buffer.from("fake exe"), exeName: plan.exeName });
		assert(Buffer.compare(zip, again) === 0, "two zips are byte-identical");
	});

	await test("prepareRelease: the lock is checked against the repo's at the ref, rbxts-rs's git packages included", async () => {
		const message = await rejects(prepareRelease(fw("--ref", "main")), /Cargo\.lock differs from fake-fw's lock at main:\n {2}rbxts_cli: .*tag=v0\.1\.1#306c3e0c\w+, the repo's lock .*tag=v0\.1\.0#0fa1528d\w+/, "the newer commit's lock");
		assert(message.startsWith(`${skeleton.replaceAll("\\", "/")}/Cargo.lock`), "names the skeleton", message);
	});

	await test("prepareRelease: the dirty check runs in the skeleton's own repo, for the skeleton only", async () => {
		write(template, { "notes.txt": "outside compiler/\n" });
		await prepareRelease(fw());
		write(skeleton, { "src/extra.rs": "// new\n" });
		await rejects(prepareRelease(fw()), /compiler has uncommitted changes:\n\?\? compiler\/src\/extra\.rs/, "an untracked skeleton file");
		await rejects(prepareRelease(fw("--allow-dirty")), /preset\.json does not match the skeleton/, "--allow-dirty, but the hash moved");
		const plan = await prepareRelease(fw("--allow-dirty", "--allow-preset-mismatch"));
		assert(plan.problems.length === 1 && plan.problems[0].startsWith('"config"'), "a test build", plan.problems.join("\n"));
		fs.rmSync(path.join(skeleton, "src", "extra.rs"));
	});

	await test("prepareRelease: a --repo that is not a git repository says so", async () => {
		const missing = path.join(ROOT, "no-such-repo");
		await rejects(prepareRelease(parseArgs(["--skeleton", skeleton, "--repo", missing])), /no-such-repo \(--repo\) is not a git repository/, "a mistyped --repo");
	});

	await test("prepareRelease: an origin that is not GitHub needs --releases and a name", async () => {
		git(fakeRepo, "remote", "set-url", "origin", "https://git.example.com/fake-fw.git");
		try {
			await rejects(prepareRelease(fw()), /no GitHub origin remote.*--version-crate/, "no version crate");
			await rejects(prepareRelease(fw("--version-crate", "fake_fw")), /origin remote \(https:\/\/git\.example\.com\/fake-fw\.git\) is not on GitHub: give --releases/, "no releases URL");
			const plan = await prepareRelease(fw("--version-crate", "fake_fw", "--releases", "https://git.example.com/fake-fw/releases"));
			equal(plan.name, "fake-fw-checkout", "the name falls back to the repo's folder");
			equal(plan.url, `https://git.example.com/fake-fw/releases/v0.1.0/fake-fw-checkout-0.1.0-${plan.platform}.zip`, "url");
		} finally {
			git(fakeRepo, "remote", "set-url", "origin", "git@github.com:example/fake-fw.git");
		}
	});

	await test("prepareRelease: a preset bin that Cargo.toml does not build, and a [patch], are refused", async () => {
		const toml = fs.readFileSync(path.join(skeleton, "Cargo.toml"), "utf8");
		try {
			write(skeleton, { "Cargo.toml": toml.replace('name = "rbxtsc-fw"\npath', 'name = "rbxtsc"\npath') });
			await rejects(prepareRelease(fw("--allow-dirty")), /preset\.json's "bin" is "rbxtsc-fw", but Cargo\.toml builds rbxtsc$/, "bin mismatch");
			write(skeleton, { "Cargo.toml": `${toml}\n[patch."https://github.com/rbxts-rs/rbxts-rs"]\n` });
			await rejects(prepareRelease(fw("--allow-dirty")), /Cargo\.toml has a \[patch\]/, "[patch]");
		} finally {
			write(skeleton, { "Cargo.toml": toml });
		}
	});
} finally {
	fs.rmSync(ROOT, { recursive: true, force: true });
}

console.log(`\n${passed} passed, ${failures} failed`);
process.exit(failures === 0 ? 0 : 1);
